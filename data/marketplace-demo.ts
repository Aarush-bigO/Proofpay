function worker(
  id: string,
  name: string,
  type: "freelancer" | "agency",
  rate: number,
  complianceScore: number,
  location: string,
  skills: string[],
  bio: string,
  avatarNum?: number
): MarketplaceWorker {
  const hash = id.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const certs = skills.slice(0, 4).map((skill, i) => ({
    skill,
    level: (i < 2 ? 2 : 1) as 1 | 2,
    source: (i % 2 === 0 ? "field" : "vr") as "vr" | "field",
  }));
  const availability: "available" | "busy" | "unavailable" = (hash % 5) === 0 ? "busy" : (hash % 7) === 0 ? "unavailable" : "available";
  const avatarIndex = avatarNum || ((hash % 14) + 1);
  return {
    id,
    name,
    avatarUrl: `/avatars/worker-${avatarIndex}.jpg`,
    type,
    license: type === "agency" || (hash % 3) !== 0 ? `KA-ELC-${10000 + (hash % 90000)}` : undefined,
    insurance: type === "agency" ? "National Insurance Commercial GL" : undefined,
    skills,
    certifications: certs,
    rate,
    availability,
    complianceScore,
    totalAnalyses: 8 + (hash % 80),
    jobHistory: [],
    location,
    bio,
    createdAt: new Date(Date.now() - (hash % 300) * 24 * 60 * 60 * 1000).toISOString(),
  };
}

